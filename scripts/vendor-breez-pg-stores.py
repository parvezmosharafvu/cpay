#!/usr/bin/env python3
"""Vendor the Breez SDK's Postgres stores (nodejs/postgres-*/*.cjs) as ESM.

The Supabase Edge bundler only ships statically imported modules, so the
runtime require.resolve("@breeztech/breez-sdk-spark/nodejs") the function
used failed in production ("Cannot find module"). This rewrites the four
CommonJS store packages into ES modules under
supabase/functions/breez-wallet/vendor/ with static imports only.
usage: vendor-breez-pg-stores.py <path to breez-sdk-spark@0.26.0/nodejs>
"""
import re, sys, pathlib
src = pathlib.Path(sys.argv[1]); out = pathlib.Path(__file__).resolve().parent.parent / "supabase/functions/breez-wallet/vendor"
PG = re.compile(r"let pg;\ntry \{.*?catch \(fallbackError\) \{.*?\n  \}\n\}\n", re.S)
for pkg in ["postgres-storage", "postgres-tree-store", "postgres-token-store", "postgres-session-store"]:
    (out / pkg).mkdir(parents=True, exist_ok=True)
    for f in sorted((src / pkg).glob("*.cjs")):
        s = f.read_text()
        head = ["// Generated by scripts/vendor-breez-pg-stores.py from @breeztech/breez-sdk-spark@0.26.0 nodejs/" + pkg + "/" + f.name + ". Do not edit."]
        if "let pg;" in s:
            s, n = PG.subn("", s, count=1); assert n == 1, (pkg, f.name, "pg block")
            head.append('import pg from "npm:pg@8.18.0";')
        if 'require("crypto")' in s:
            s = re.sub(r'^\s*const crypto = require\("crypto"\);\n', "", s, flags=re.M)
            head.append('import crypto from "node:crypto";')
        if 'require("fs")' in s:
            s = s.replace('require("fs")', "__fs"); head.append('import * as __fs from "node:fs";')
        if re.search(r"\bBuffer\b", s):
            head.append('import { Buffer } from "node:buffer";')  # not a global on Supabase Edge
        s = re.sub(r'^const (\{[^}]*\}) = require\("\./(\w+)\.cjs"\);', r'import \1 from "./\2.mjs";', s, flags=re.M)
        s = re.sub(r'^module\.exports = (\{.*?\});', lambda m: "export " + m.group(1) + ";", s, flags=re.M | re.S)
        assert "require(" not in s and "module.exports" not in s, (pkg, f.name)
        (out / pkg / f.name.replace(".cjs", ".mjs")).write_text("\n".join(head) + "\n" + s)
print("vendored to", out)
